"""
VANET Collision Warning & Traffic Management - Phase 5
Warning Generator Module

This module takes a CollisionEvent generated by the CollisionDetector and creates
structured, standardized warning messages (ETSI DENM-style). It coordinates with
the AODV networking engine to trigger packet transmission.

Standards Context:
-----------------
In vehicular networks (VANETs), standard warning messages are based on ETSI EN 302 637-3
Decentralized Environmental Notification Messages (DENM):
- ActionID / EventID: Unique identification of the hazard event
- ReferenceTime: Detection timestamp
- EventPosition: Road/Lane coordinates
- SituationContainer: CauseCode (e.g., Dangerous Situation, Emergency Braking)
- Target: Intended recipient(s) - e.g., following vehicle behind the hazard
"""

from dataclasses import dataclass, asdict
from typing import Dict, Any, Optional
from phase5_collision_detection.collision_detector import CollisionEvent


@dataclass
class StructuredWarningMessage:
    event_id: str
    timestamp: float
    sender_id: str
    sender_ip: str
    target_id: str
    target_ip: str
    warning_type: str
    risk_level: str
    gap_m: float
    closing_speed_mps: float
    ttc_s: float
    lane_id: str
    payload_bytes: int = 256

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class WarningGenerator:
    """
    Transforms detected collision events into structured warning messages
    and prepares them for injection into the AODV routing protocol layer.
    """

    def __init__(self, verbose: bool = True):
        self.verbose = verbose
        self.generated_warnings_log = []

    def generate(self, event: CollisionEvent) -> Optional[StructuredWarningMessage]:
        """
        Create a StructuredWarningMessage from a CollisionEvent.
        Only generates a message if event.warning_generated is True.
        """
        if not event.warning_generated:
            return None

        # Determine Warning Type according to severity and scenario
        if event.risk_level == "CRITICAL":
            warning_type = "EMERGENCY_BRAKE_WARNING"
        elif event.risk_level == "HIGH":
            warning_type = "FORWARD_COLLISION_WARNING"
        else:
            warning_type = "HEADWAY_ALERT"

        # Notice: In rear-end hazard, either the Leader warns the Follower,
        # or Follower's forward sensing triggers notification/dissemination.
        # For VANET V2V cooperative warning (ETSI DENM), Leader (or sensing car)
        # broadcasts/unicasts warning to Follower.
        # Sender: Leader (or Sensing Node) -> Receiver: Follower
        sender_id = event.leader_id
        sender_ip = event.leader_ip
        target_id = event.follower_id
        target_ip = event.follower_ip

        msg = StructuredWarningMessage(
            event_id=event.event_id,
            timestamp=event.timestamp,
            sender_id=sender_id,
            sender_ip=sender_ip,
            target_id=target_id,
            target_ip=target_ip,
            warning_type=warning_type,
            risk_level=event.risk_level,
            gap_m=event.gap_m,
            closing_speed_mps=event.closing_speed_mps,
            ttc_s=event.ttc_s,
            lane_id=event.lane_id,
            payload_bytes=256
        )

        self.generated_warnings_log.append(msg.to_dict())

        if self.verbose:
            print(
                f"  [WARNING GENERATOR] Created {warning_type} ({event.risk_level}) | "
                f"From {sender_id} ({sender_ip}) -> To {target_id} ({target_ip}) | "
                f"TTC: {event.ttc_s:.2f}s | Gap: {event.gap_m:.1f}m"
            )

        return msg
